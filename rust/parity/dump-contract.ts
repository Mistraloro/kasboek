// Dumps the contract of the app (src/shared/contract.ts and the op tables of src/core/ops.ts and src/main/ipc.ts) into
// the JSON that kb-core's tests compare its op registry against: names, mutates / assistant / public flags, descriptions,
// the input JSON Schemas (generated like assistantTools() does) and the names of the output types.
// Run through contract.spec.ts (KB_WRITE_CONTRACT=1 writes rust/crates/kb-core/contract.json).
import { readFileSync } from 'node:fs'
import { resolve } from 'node:path'
import { z } from 'zod'
import { contract, PUBLIC_OPS, type ContractEntry, type OpName } from '@shared/contract'
import { CURRENCIES } from '@shared/currency'
import { ACCOUNT_KINDS } from '@shared/types'
import { CURRENCY_POSITIONS, CURRENCY_STYLES, DATE_PATTERNS, DECIMAL_SEPARATORS, DEFAULT_FORMATS, GROUPINGS, GROUP_SEPARATORS, NEGATIVE_STYLES, TIME_FORMATS } from '@shared/format'
import { GRAPHICS_CHOICES } from '@shared/graphics'
import { LANGUAGE_CODES } from '@shared/languages'
import { DEFAULT_SETTINGS } from '@core/settings'
import type { OpTable } from '@core/ops'

const root = resolve(import.meta.dirname, '../..')

/** `output: out<Type>()` of every op, as written in contract.ts: the outputs are TypeScript types, they have no runtime schema. */
function outputTypes(): Record<string, string> {
  const src = readFileSync(resolve(root, 'src/shared/contract.ts'), 'utf8')
  const found: Record<string, string> = {}
  // Every entry starts with `'op.name': {`; its output is the first `out<...>()` before the next entry.
  const entries = src.split(/\n {2}(?:\/\*\*[^\n]*\*\/\n {2})?(?=')/)
  for (const e of entries) {
    const name = /^'([a-zA-Z.]+)': \{/.exec(e)?.[1]
    const out = /output: out<(.*)>\(\)/s.exec(e)?.[1]
    if (name && out) found[name] = out.split('\n')[0]!.replace(/>\(\)\s*(\}\s*)?,?$/, '').replace(/\s+/g, ' ').trim()
  }
  return found
}

export function dumpContract(allOps: OpTable): unknown {
  const types = outputTypes()
  const ops = (Object.keys(contract) as OpName[]).map((name) => {
    const entry = contract[name] as ContractEntry
    const def = allOps[name]
    if (!def) throw new Error(`no handler table entry for ${name}`)
    const schema = z.toJSONSchema(entry.input, { io: 'input', unrepresentable: 'any' }) as Record<string, unknown>
    delete schema['$schema']
    return {
      name,
      mutates: def.mutates,
      assistant: def.assistant,
      public: PUBLIC_OPS.includes(name),
      description: entry.description ?? null,
      outputType: types[name] ?? null,
      input: schema
    }
  })
  return {
    note: 'Generated by rust/parity/dump-contract.ts (KB_WRITE_CONTRACT=1 npx vitest run --config rust/parity/vitest.config.ts contract). Do not edit.',
    opCount: ops.length,
    enums: {
      currencies: CURRENCIES,
      accountKinds: [...ACCOUNT_KINDS],
      languages: LANGUAGE_CODES,
      graphics: [...GRAPHICS_CHOICES],
      format: {
        decimal: DECIMAL_SEPARATORS,
        group: GROUP_SEPARATORS,
        grouping: GROUPINGS,
        currencyPosition: CURRENCY_POSITIONS,
        currencyStyle: CURRENCY_STYLES,
        negative: NEGATIVE_STYLES,
        date: [...DATE_PATTERNS],
        time: TIME_FORMATS
      }
    },
    defaults: { settings: DEFAULT_SETTINGS, formats: DEFAULT_FORMATS },
    ops
  }
}
