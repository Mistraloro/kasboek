// Generates the icon set: every lucide icon the React renderer imports (found by scanning src/renderer for
// `from 'lucide-react'`), as standalone SVG files in assets/icons plus ui/icons.slint (the `Icons` global).
// Usage: node tools/make-icons.mjs   (run from anywhere; reads <repo>/node_modules/lucide-react, ISC licence)
// The property name of an icon is the canonical lucide file name (alias names such as CheckCircle2 resolve to it).
import { mkdirSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const kbUi = join(here, '..')
const root = join(kbUi, '..', '..', '..')
const out = join(kbUi, 'assets', 'icons')
const lucide = join(root, 'node_modules', 'lucide-react', 'dist', 'esm')

// Extra variants the components need: [lucide file, output name, stroke width].
const extras = [['check', 'check-3', 3]]

function* sources(dir) {
  for (const name of readdirSync(dir)) {
    const path = join(dir, name)
    if (statSync(path).isDirectory()) yield* sources(path)
    else if (/\.(ts|tsx)$/.test(name)) yield path
  }
}

// Component name (and every alias) -> icon file stem, from lucide-react's own export list.
const fileOf = new Map()
for (const m of readFileSync(join(lucide, 'lucide-react.mjs'), 'utf8').matchAll(/^export \{([^}]*)\} from '\.\/icons\/([^']+)\.mjs'/gm)) {
  for (const a of m[1].matchAll(/default as (\w+)/g)) fileOf.set(a[1], m[2])
}

// Icons are offered under the file name and under the kebab-case of every name the renderer imports (AlertCircle ->
// alert-circle), so a React name is easy to find. alias name -> file stem.
const kebab = (name) => name.replace(/([a-z0-9])([A-Z])/g, '$1-$2').replace(/([a-zA-Z])([0-9])/g, '$1-$2').toLowerCase()
const aliases = new Map()
const used = new Set()
for (const file of sources(join(root, 'src', 'renderer', 'src'))) {
  for (const m of readFileSync(file, 'utf8').matchAll(/import\s*\{([^}]*)\}\s*from\s*'lucide-react'/g)) {
    for (const part of m[1].split(',')) {
      const name = part.trim().replace(/^type\s+/, '').split(/\s+as\s+/)[0]
      if (!name) continue
      if (!fileOf.has(name)) throw new Error(`lucide-react has no icon ${name} (imported in ${file})`)
      used.add(fileOf.get(name))
      aliases.set(kebab(name), fileOf.get(name))
    }
  }
}

rmSync(out, { recursive: true, force: true })
mkdirSync(out, { recursive: true })
const names = []
const write = async (stem, name, width) => {
  const mod = await import(pathToFileURL(join(lucide, 'icons', `${stem}.mjs`)).href)
  const body = mod.__iconData.node
    .map(([tag, attrs]) => `<${tag} ${Object.entries(attrs).filter(([k]) => k !== 'key').map(([k, v]) => `${k}="${v}"`).join(' ')}/>`)
    .join('')
  writeFileSync(
    join(out, `${name}.svg`),
    `<svg xmlns="http://www.w3.org/2000/svg" width="24" height="24" viewBox="0 0 24 24" fill="none" stroke="#000" stroke-width="${width}" stroke-linecap="round" stroke-linejoin="round">${body}</svg>\n`
  )
  names.push(name)
}
for (const stem of [...used].sort()) await write(stem, stem, 2)
for (const [stem, name, width] of extras) await write(stem, name, width)
// The Kasboek mark (src/renderer/src/components/Mark.tsx), 520x624 viewBox.
writeFileSync(
  join(out, 'mark.svg'),
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="240 200 520 624" fill="#000"><path d="M492 512 L704 724" stroke="#000" stroke-opacity=".5" stroke-width="120" stroke-linecap="round"/><path d="M492 512 L704 300" stroke="#000" stroke-width="120" stroke-linecap="round"/><rect x="292" y="252" width="120" height="520" rx="60"/></svg>\n`
)
names.push('mark')
names.sort()
for (const [alias, stem] of [...aliases].sort()) if (!names.includes(alias)) aliases.set(alias, stem)
const aliasLines = [...aliases].filter(([alias]) => !names.includes(alias))

writeFileSync(
  join(kbUi, 'ui', 'icons.slint'),
  [
    '// Generated by tools/make-icons.mjs. Do not edit. Use with `Icon { source: Icons.eye; }`.',
    'export global Icons {',
    ...names.map((n) => `    out property <image> ${n}: @image-url("../assets/icons/${n}.svg");`),
    '    // The names the React renderer imports them under:',
    ...aliasLines.map(([alias, stem]) => `    out property <image> ${alias}: ${stem};`),
    '}',
    ''
  ].join('\n')
)
console.log(`${names.length} icons, ${aliasLines.length} alias names`)
