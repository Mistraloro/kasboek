#!/usr/bin/env python3
"""Builds the static font instances Slint embeds, from the variable fonts the Electron app bundles.

Needs: pip install fonttools brotli opentype-feature-freezer
Input : tools/fonts.json (the one place that names the fonts) and
        node_modules/@fontsource-variable/<package>/files/<package>-latin-wght-normal.woff2 (OFL-1.1)
Output: assets/fonts/*.ttf   (Latin subset as shipped by fontsource), assets/fonts/<Family>-OFL.txt,
        ui/fonts.slint       (imports of the TTFs and the `Fonts` global with the family names)

A family with "freeze": "tnum" gets that OpenType feature frozen into the glyphs (Inter Num, the renderer's `.num`
class), because Slint has no font-feature-settings.

styles.css asks for cv11 and ss01, but the fontsource latin subset has no such features (its GSUB only has
calt, ccmp, dnom, frac, locl, numr, pnum, tnum), so Chromium renders neither today. Nothing to freeze for them.
"""
import json
import shutil
import subprocess
import sys
from pathlib import Path

from fontTools.ttLib import TTFont
from fontTools.varLib import instancer

KB_UI = Path(__file__).resolve().parents[1]
ROOT = KB_UI.parents[2]
OUT = KB_UI / "assets" / "fonts"
SRC = ROOT / "node_modules" / "@fontsource-variable"
STYLE = {400: "Regular", 500: "Medium", 600: "SemiBold"}


def rename(font: TTFont, family: str, weight: int) -> None:
    style = STYLE[weight]
    full = f"{family} {style}"
    for rec in list(font["name"].names):
        if rec.nameID in (1, 2, 3, 4, 6, 16, 17, 21, 22, 25):
            font["name"].removeNames(nameID=rec.nameID)
    n = font["name"]
    ps = full.replace(" ", "")
    for nid, val in ((1, family), (2, "Regular"), (3, ps), (4, full), (6, ps), (16, family), (17, style)):
        n.setName(val, nid, 3, 1, 0x409)
        n.setName(val, nid, 1, 0, 0)
    font["OS/2"].usWeightClass = weight


def instance(woff2: Path, weight: int, tmp: Path) -> Path:
    vf = TTFont(woff2)
    vf.flavor = None
    inst = instancer.instantiateVariableFont(vf, {"wght": weight})
    path = tmp / f"{woff2.stem}-{weight}.ttf"
    inst.save(path)
    return path


def freeze(src: Path, features: str, dst: Path) -> None:
    subprocess.run(["pyftfeatfreeze", "-f", features, str(src), str(dst)], check=True, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)


def main() -> None:
    config = json.loads((Path(__file__).parent / "fonts.json").read_text())
    OUT.mkdir(parents=True, exist_ok=True)
    tmp = OUT / ".tmp"
    tmp.mkdir(exist_ok=True)
    files: list[str] = []
    licences: set[str] = set()
    for fam in config["families"]:
        family = fam["family"]
        stem = family.replace(" ", "")
        woff2 = SRC / fam["package"] / "files" / f"{fam['package']}-latin-wght-normal.woff2"
        for w in fam["weights"]:
            inst = instance(woff2, w, tmp)
            dst = OUT / f"{stem}-{STYLE[w]}.ttf"
            if fam.get("freeze"):
                freeze(inst, fam["freeze"], dst)
            else:
                shutil.copy(inst, dst)
            f = TTFont(dst)
            rename(f, family, w)
            f.save(dst)
            files.append(dst.name)
        if not fam.get("freeze") and fam["package"] not in licences:
            licences.add(fam["package"])
            shutil.copy(SRC / fam["package"] / "LICENSE", OUT / f"{stem}-OFL.txt")
    for p in tmp.iterdir():
        p.unlink()
    tmp.rmdir()

    slint = [
        "// Generated by tools/make-fonts.py from tools/fonts.json. Do not edit.",
        *(f'import "../assets/fonts/{name}";' for name in files),
        "",
        "// The family names are the only place the rest of the design system learns them from.",
        "export global Fonts {",
        *(f'    out property <string> {fam["role"]}: "{fam["family"]}";' for fam in config["families"]),
        "}",
        "",
    ]
    (KB_UI / "ui" / "fonts.slint").write_text("\n".join(slint))
    for name in files:
        print(f"{name}\t{(OUT / name).stat().st_size}")


if __name__ == "__main__":
    sys.exit(main())
